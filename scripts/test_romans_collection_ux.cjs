const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const source=fs.readFileSync(path.join(__dirname,'../assets/js/sinjira-reads-v24-4-61.js'),'utf8');
const start=source.indexOf('function progressValue('),end=source.indexOf('async function load()',start);
assert.ok(start>=0&&end>start);
const api=vm.runInNewContext(source.slice(start,end)+'\n({progressValue,progressBar,requireRows,actionLock})');
assert.equal(api.progressValue(null),null);
assert.equal(api.progressValue('invalid'),null);
assert.equal(api.progressValue(0),0);
assert.equal(api.progressValue(120),100);
assert.equal(api.progressValue(-5),0);
assert.match(api.progressBar(45),/<progress max="100" value="45"/);
assert.equal(api.progressBar(null),'');
assert.throws(()=>api.requireRows({data:null}),/invalide/);
assert.equal(api.requireRows({data:[]}).length,0);
const lock=api.actionLock();assert.equal(lock.start(),true);assert.equal(lock.start(),false);
lock.finish();assert.equal(lock.start(),true);lock.finish(true);assert.equal(lock.start(),false);
assert.match(source,/ignoreDuplicates:true/);
assert.match(source,/library=requireRows\(await readLibrary\(\)\)/);
assert.match(source,/Modification confirmée, mais collection non actualisée/);
assert.match(source,/Voir le statut de la démo/);
console.log('OK collection: progression, réponses invalides, verrou, protection des données existantes.');
